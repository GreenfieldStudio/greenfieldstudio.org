// One landing page per Greenfield Ambience film: /ambience/<slug>/
//
// Used by tools/sync-ambience.mjs (never run on its own). Everything on a page comes from the
// film's own YouTube text in films.json, so a page can't claim more than the video does:
//   - the first paragraph of the description is the lede and the meta description;
//   - later paragraphs are kept unless they hold a link, a hashtag or an @handle (those are
//     YouTube housekeeping, not copy);
//   - "0:00 Label" lines become the chapter list;
//   - length, 4K and frame rate are read from the title and description, like the film cards.
// "No Loops" is the one claim a description can make that only a test can back up, so a page shows
// it ONLY when tools/film-pages.json carries the repeat-check record for that film's id.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { esc, clock as clock0, matchEol } from './youtube.mjs';
import { signupSection } from '../signup.mjs';
const clock = (s) => (s === 0 ? '0:00' : clock0(s));

export const SITE_URL = 'https://greenfieldstudio.org';
export const CHANNEL = 'https://www.youtube.com/@Greenfield.Ambience';
export const MARK = '<!-- generated by tools/sync-ambience.mjs: edit the tool, not this page -->';

const PLAY = '<svg viewBox="0 0 16 16" aria-hidden="true" focusable="false"><path d="M4.5 2.6v10.8l8.8-5.4z" fill="currentColor"/></svg>';
const BRAND = '<svg viewBox="0 0 38 22" aria-hidden="true" focusable="false"><circle cx="4.5" cy="17" r="3.6" fill="#efe8d6"/><circle cx="11" cy="9.2" r="1.1" fill="#a19b8a"/><circle cx="16.8" cy="5.4" r="1.1" fill="#a19b8a"/><circle cx="23" cy="5.2" r="1.1" fill="#a19b8a"/><circle cx="28.4" cy="9" r="1.1" fill="#a19b8a"/><circle cx="32.5" cy="17" r="4.3" fill="#050b07" stroke="#efe8d6" stroke-width="1.4"/></svg>';

/** "Coral Reef Aquarium 4K 60fps | 1 Hour Relaxing…" → "Coral Reef Aquarium"; a hand-set displayTitle wins. */
export const displayTitle = (f) => f.displayTitle || f.title.split(/\s+[|·—–]\s+/)[0].replace(/\s+4K(\s+60\s*fps)?$/i, '').trim() || f.title;

export const slugify = (s) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48).replace(/-+$/, '') || 'film';

/** Give every film a slug that never changes once it has one (so shared links keep working). */
export function ensureSlugs(db) {
  const taken = new Set(db.films.map((f) => f.slug).filter(Boolean));
  let added = 0;
  for (const f of db.films) {
    if (f.slug) continue;
    let s = slugify(displayTitle(f)), n = 2;
    while (taken.has(s)) s = `${slugify(displayTitle(f))}-${n++}`;
    f.slug = s;
    taken.add(s);
    added++;
  }
  return added;
}

/** Length in seconds: the watch page's number, else a plain "3 Hours" in the film's own title. */
export function secondsOf(f) {
  if (f.seconds) return f.seconds;
  const m = /(\d+(?:\.\d+)?)\s*(?:hours?|hrs?)\b/i.exec(f.title);
  return m ? Math.round(Number(m[1]) * 3600) : null;
}
const longLength = (s) => (s >= 5400 ? `${+(s / 3600).toFixed(1)} hours` : s >= 3300 && s < 3900 ? '1 hour' : `${Math.round(s / 60)} minutes`);
const iso = (s) => `PT${Math.floor(s / 3600)}H${Math.floor((s % 3600) / 60)}M${s % 60}S`;

function specs(f) {
  const text = `${f.title}\n${f.description || ''}`;
  const fps = /(\d{2,3})\s*(?:fps|frames per second)/i.exec(text);
  return {
    res: /3840\s*[×x]\s*2160/.test(text) ? '3840 × 2160' : /\b4K\b/i.test(text) ? '4K' : '',
    fps: fps ? `${fps[1]} fps` : '',
    noMusic: /no music/i.test(text),
  };
}

/**
 * A film whose full master has no passing repeat check (tools/film-pages.json) must not say "no loops" /
 * "never repeats" on this site, even if its YouTube text does. Known phrasings are cut cleanly; any other
 * sentence that still makes the claim is dropped.
 */
const LOOP_WORDS = /\bloops?\b|\bnever repeats?\b|\bnothing repeats\b|\bnever (?:see|hear) the same\b/i;
export function softenLoops(text) {
  let t = text
    .replace(/\bNothing in this video loops:\s*(\w)/g, (_, c) => c.toUpperCase())
    .replace(/,?\s*so (?:it|nothing) never repeats|,\s*so nothing repeats(?::[^.]*)?/gi, '')
    .replace(/\s*\bNo loops\.?/gi, '');
  if (LOOP_WORDS.test(t)) t = t.split(/(?<=[.!?])\s+/).filter((x) => !LOOP_WORDS.test(x)).join(' ');
  return t.replace(/\s+([.,])/g, '$1').trim();
}

/** Split the description into { summary, body: [{p}|{ul}], chapters: [{t, label}] }. `soften`: drop loop claims. */
export function parseDescription(f, soften = false) {
  const text0 = (f.description || '').replace(/\r/g, '').trim();
  const text = soften ? text0.split('\n').map((l) => (LOOP_WORDS.test(l) ? softenLoops(l) : l)).join('\n') : text0;
  const blocks = text.split(/\n{2,}/).map((b) => b.trim()).filter(Boolean);
  const chapters = [];
  const body = [];
  const chap = /^((?:\d{1,2}:)?\d{1,2}:\d{2})\s+(.+)$/;
  const toSec = (t) => t.split(':').reduce((a, n) => a * 60 + Number(n), 0);
  blocks.forEach((b, i) => {
    const lines = b.split('\n').map((l) => l.trim());
    if (lines.every((l) => chap.test(l))) { lines.forEach((l) => { const m = chap.exec(l); chapters.push({ s: toSec(m[1]), label: m[2] }); }); return; }
    if (i === 0) return; // the summary, used separately
    if (/https?:\/\/|(^|\s)#\w|(^|\s)@\w/.test(b)) return; // links, hashtags and handles are housekeeping
    const out = [];
    let list = null;
    for (const l of lines) {
      if (/^[-•]\s+/.test(l)) { (list ||= []).push(l.replace(/^[-•]\s+/, '')); continue; }
      if (list) { out.push({ ul: list }); list = null; }
      out.push({ p: l });
    }
    if (list) out.push({ ul: list });
    body.push(...out);
  });
  const first = blocks[0] || f.title;
  // chapters need to start at 0:00 and be at least three, or YouTube itself would not show them
  const ok = chapters.length >= 3 && chapters[0].s === 0 ? chapters : [];
  return { summary: first.replace(/\n+/g, ' '), body, chapters: ok };
}

