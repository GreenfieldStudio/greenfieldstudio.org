/** One film's page, HTML. `others` = the other films, newest first. `cfg` = tools/film-pages.json entry. */
export function renderFilmPage(f, others, cfg = {}) {
  const name = displayTitle(f);
  const s = secondsOf(f);
  const sp = specs(f);
  const d = parseDescription(f, !cfg.repeatCheck);
  const url = `${SITE_URL}/ambience/${f.slug}/`;
  const watch = `https://www.youtube.com/watch?v=${f.id}`;
  const title = `${name}${s ? ` · ${longLength(s)}${sp.res ? ' in 4K' : ''}` : sp.res ? ' · 4K' : ''} · Greenfield Ambience`;
  const firstP = (d.body.find((b) => b.p) || {}).p || '';
  const desc = clip(d.summary.length < 90 && firstP ? `${d.summary} ${firstP}` : d.summary, 158);
  const thumb = `../../assets/media/ambience/films/${f.id}`;
  const spec = [s ? longLength(s) : '', sp.res ? '4K' : '', sp.fps, sp.noMusic ? 'no music' : ''].filter(Boolean).join(' · ');

  const facts = [
    s && ['length', clock(s)],
    sp.res && ['resolution', sp.res],
    sp.fps && ['frame rate', sp.fps],
    sp.noMusic && ['music', 'none'],
    cfg.repeatCheck && ['loops', 'none'],
    ['published', f.published],
    ['made by', 'Greenfield Studio'],
  ].filter(Boolean);

  const ld = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'VideoObject',
        name: f.title,
        description: d.summary,
        thumbnailUrl: `${SITE_URL}/assets/media/ambience/films/${f.id}-1280.webp`,
        uploadDate: f.published,
        ...(s ? { duration: iso(s) } : {}),
        url,
        embedUrl: `https://www.youtube-nocookie.com/embed/${f.id}`,
        publisher: { '@type': 'Organization', name: 'Greenfield Studio', url: `${SITE_URL}/` },
        ...(d.chapters.length ? {
          hasPart: d.chapters.map((c, i) => ({
            '@type': 'Clip', name: c.label, startOffset: c.s,
            ...(d.chapters[i + 1] ? { endOffset: d.chapters[i + 1].s } : s ? { endOffset: s } : {}),
            url: `${watch}&t=${c.s}s`,
          })),
        } : {}),
      },
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Greenfield Ambience', item: `${SITE_URL}/ambience/` },
          { '@type': 'ListItem', position: 2, name, item: url },
        ],
      },
    ],
  };

  const bodyHtml = d.body.map((b) => (b.p ? `<p>${esc(b.p)}</p>` : `<ul>${b.ul.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`)).join('\n          ');
  const chaptersHtml = d.chapters.length ? `
    <section class="section" id="chapters" aria-labelledby="chapters-title">
      <div class="wrap">
        <p class="fig"><span>fig. 02</span> <b>chapters</b></p>
        <h2 class="h2" id="chapters-title">Jump to a moment</h2>
        <ol class="chapters">
${d.chapters.map((c) => `          <li><a href="${watch}&amp;t=${c.s}s" data-start="${c.s}" rel="noopener"><span class="anno">${clock(c.s)}</span> ${esc(c.label)}</a></li>`).join('\n')}
        </ol>
      </div>
    </section>` : '';
  const more = others.slice(0, 3);
  const moreHtml = more.length ? `
    <section class="section" id="more" aria-labelledby="more-title">
      <div class="wrap">
        <p class="fig"><span>fig. ${d.chapters.length ? '03' : '02'}</span> <b>more films</b></p>
        <h2 class="h2" id="more-title">Leave another one running</h2>
        <div class="films" style="margin-top:32px">
${more.map((o) => `          <a class="film" href="../${o.slug}/">
            <span class="film-media">
              <img src="../../assets/media/ambience/films/${o.id}-640.webp" width="1280" height="720" loading="lazy" decoding="async" alt="">
              <span class="film-play" aria-hidden="true"><span class="play-disc">${PLAY}</span></span>${secondsOf(o) ? `\n              <span class="film-len">${clock(secondsOf(o))}</span>` : ''}
            </span>
            <h3>${esc(displayTitle(o))}</h3>
          </a>`).join('\n')}
        </div>
        <p style="margin-top:28px"><a class="link-arrow" href="../">All films</a></p>
      </div>
    </section>` : '';

  return `<!doctype html>
${MARK}
<html lang="en">
${head({ title, desc, url, ogImage: `${SITE_URL}/assets/media/ambience/films/${f.id}-og.jpg`, ld })}
<body>
  <a class="skip-link" href="#main">Skip to content</a>

  ${SHELL_TOP}

  <main id="main">
    <section class="section" style="padding-top:clamp(32px,6vw,72px)" aria-labelledby="film-title">
      <div class="wrap">
        <p class="fig"><span>greenfield ambience</span> <b><a href="../">all films</a></b></p>
        <h1 class="h2" id="film-title">${esc(name)}</h1>
        <p class="lede">${esc(d.summary)}</p>
        <p class="anno" style="margin:14px 0 28px">${esc(spec)}${spec ? ' · ' : ''}on YouTube</p>

        <a class="embed" href="${watch}" aria-label="Play the film: ${esc(name)}" data-embed="${f.id}" data-film-title="${esc(f.title)}" rel="noopener">
          <img src="${thumb}-1280.webp" srcset="${thumb}-640.webp 640w, ${thumb}-1280.webp 1280w" sizes="(max-width: 1180px) 100vw, 1180px" width="1280" height="720" fetchpriority="high" decoding="async" alt="Thumbnail of the film ${esc(name)}">
          <span class="film-play" aria-hidden="true"><span class="play-disc">${PLAY}</span></span>${s ? `\n          <span class="film-len">${clock(s)}</span>` : ''}
        </a>
        <div class="btn-row" style="margin-top:24px">
          <a class="btn btn--brass btn--lg" href="${CHANNEL}?sub_confirmation=1" rel="noopener">Subscribe on YouTube</a>
          <a class="btn btn--lg" href="${watch}" rel="noopener">Watch on YouTube</a>
        </div>
        <p class="muted" style="margin-top:14px;font-size:15px">The player loads from YouTube only when you press play.</p>
      </div>
    </section>

    <section class="section" aria-labelledby="about-title">
      <div class="wrap split">
        <div class="prose">
          <p class="fig"><span>fig. 01</span> <b>about this film</b></p>
          <h2 class="h2" id="about-title">What you'll see and hear</h2>
          ${bodyHtml}
          <p><a class="link-arrow" href="../">All Greenfield Ambience films</a></p>
        </div>
        <aside class="readout" aria-label="The film at a glance">
          <dl>
${facts.map(([k, v]) => `            <dt>${k}</dt><dd>${esc(v)}</dd>`).join('\n')}
          </dl>${cfg.repeatCheck ? `\n          <span class="anno">repeat check passed ${esc(cfg.repeatCheck)}</span>` : ''}
        </aside>
      </div>
    </section>${chaptersHtml}${moreHtml}${signupSection('../../') ? `
    ${signupSection('../../')}` : ''}
  </main>

  <footer class="site-footer"></footer>
</body>
</html>
`;
}

/** The part of a page that sync-chrome rewrites is masked, so a check compares only what this tool owns. */
export const mask = (html) => html.replace(/\r/g, '')
  .replace(/<nav class="nav" aria-label="Main">[\s\S]*?<\/nav>/, '<nav class="nav" aria-label="Main"></nav>')
  .replace(/<footer class="site-footer">[\s\S]*?<\/footer>/, '<footer class="site-footer"></footer>');

/** 1200 × 630 share image from the 1280 thumbnail (link-preview scrapers do not all take WebP). */
function makeOg(dir, id) {
  const out = join(dir, `${id}-og.jpg`);
  if (existsSync(out)) return true;
  const x = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', join(dir, `${id}-1280.webp`), '-vf', 'scale=1200:630:force_original_aspect_ratio=increase,crop=1200:630', '-q:v', '3', out]);
  return x.status === 0;
}

/**
 * Write (or, with check, compare) every film's page, the share images and the sitemap block.
 * Returns the list of problems when checking.
 */
export function syncFilmPages({ site, db, cfgFile, check }) {
  const dir = join(site, 'assets', 'media', 'ambience', 'films');
  const cfg = existsSync(cfgFile) ? JSON.parse(readFileSync(cfgFile, 'utf8')) : {};
  const problems = [];
  const films = db.films.filter((f) => f.slug);
  for (const f of films) {
    const others = films.filter((o) => o.id !== f.id);
    const page = join(site, 'ambience', f.slug, 'index.html');
    const html = renderFilmPage(f, others, cfg[f.id]);
    if (check) {
      if (!existsSync(page)) { problems.push(`missing ambience/${f.slug}/index.html`); continue; }
      const have = readFileSync(page, 'utf8');
      if (mask(have) !== mask(html)) problems.push(`ambience/${f.slug}/index.html differs from films.json`);
      if (!existsSync(join(dir, `${f.id}-og.jpg`))) problems.push(`missing share image ${f.id}-og.jpg`);
    } else {
      if (!makeOg(dir, f.id)) throw new Error(`no share image for ${f.id}`);
      mkdirSync(join(site, 'ambience', f.slug), { recursive: true });
      const have = existsSync(page) ? readFileSync(page, 'utf8') : '';
      // keep the menu and footer sync-chrome wrote; sync-chrome refreshes them on its own run
      let keep = html;
      const nav = have.match(/<nav class="nav" aria-label="Main">[\s\S]*?<\/nav>/), foot = have.match(/<footer class="site-footer">[\s\S]*?<\/footer>/);
      if (nav) keep = keep.replace('<nav class="nav" aria-label="Main"></nav>', () => nav[0]);
      if (foot) keep = keep.replace('<footer class="site-footer"></footer>', () => foot[0]);
      if (mask(have) !== mask(keep) || !have) writeFileSync(page, matchEol(keep, have || '\n'));
    }
  }
  // pages of films that left the site
  const slugs = new Set(films.map((f) => f.slug));
  for (const e of readdirSync(join(site, 'ambience'), { withFileTypes: true })) {
    if (!e.isDirectory() || slugs.has(e.name)) continue;
    const p = join(site, 'ambience', e.name, 'index.html');
    if (!existsSync(p) || !readFileSync(p, 'utf8').includes(MARK)) continue; // only ever remove pages this tool made
    if (check) problems.push(`ambience/${e.name}/ belongs to a film that is no longer listed`);
    else rmSync(join(site, 'ambience', e.name), { recursive: true, force: true });
  }
  // sitemap block
  const smPath = join(site, 'sitemap.xml');
  const sm = readFileSync(smPath, 'utf8');
  const block = films.map((f) => `  <url><loc>${SITE_URL}/ambience/${f.slug}/</loc><lastmod>${f.published}</lastmod></url>`).join('\n');
  const re = /(<!-- films:start -->)[\s\S]*?(<!-- films:end -->)/;
  if (!re.test(sm)) throw new Error('sitemap.xml has no films:start / films:end markers');
  const eol = sm.includes('\r\n') ? '\r\n' : '\n';
  const next = sm.replace(re, (_, a, b) => `${a}${eol}${block.replace(/\n/g, eol)}${eol}  ${b}`);
  if (check) { if (next.replace(/\r/g, '') !== sm.replace(/\r/g, '')) problems.push('sitemap.xml differs from films.json'); }
  else if (next !== sm) writeFileSync(smPath, next);
  return problems;
}
